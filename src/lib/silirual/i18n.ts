const dicts: Record<LangCode, Dict> = { en, hi, bn, as, mni };

export function translate(lang: LangCode, key: string): string {
  return dicts[lang]?.[key] ?? en[key] ?? key;
}

export function speechLocale(lang: LangCode): string {
  return LANGUAGES.find((l) => l.code === lang)?.speech ?? "en-IN";
}
